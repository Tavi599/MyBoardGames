/* ── вибірка й сортування ────────────────────────── */
function effScore(g){
  if(ui.count === "all") return g.score == null ? null : g.score;
  const v = g.byCount ? g.byCount[ui.count] : null;
  return v == null ? null : v;
}
function fitsCount(g, який){
  const с = який == null ? ui.count : який;
  if(с === "all") return true;
  // Поставлена оцінка сильніша за межі: якщо ви так грали — воно грається.
  if(g.byCount && g.byCount[с] != null) return true;
  const {від: mn, до: mx} = склад(g);
  if(mn == null && mx == null) return true;
  if(с === "5+") return mx == null || mx > 5;
  const c = +с;
  return (mn == null || mn <= c) && (mx == null || mx >= c);
}
/* ── що прибрати з полиці зовсім ──────────────────────────────────────
   Це не фільтр, а звуження самої полиці, і різниця тут суттєва: підсумки
   нагорі рахуються по shelf(), тож прибране не потрапляє ні в «ігор на
   полиці», ні в середню оцінку. Саме цього від «приховати» й чекаєш —
   на відміну від фільтра, який лише звужує показане.

   Позначок можна поставити скільки завгодно: доповнення, позбуті коробки
   й те, у що граєш лише онлайн, — це три різні причини не хотіти бачити
   гру в списку, і вони не виключають одна одну. */
const ХОВАНКИ = [
  {ключ: "exp", підпис: "доповнення", пасує: (g) => !!g.expansion},
  {ключ: "позбувся", підпис: "позбуті коробки",
   пасує: (g) => stats(g).indexOf("позбувся") >= 0},
  {ключ: "онлайн", підпис: "лише онлайн",
   пасує: (g) => stats(g).indexOf("онлайн") >= 0},
  {ключ: "філер", підпис: "маленькі філери",
   пасує: (g) => stats(g).indexOf("філер") >= 0},
];
function shelf(){
  const х = ui.hide;
  if(!х || !х.size) return games;
  return games.filter((g) => !ХОВАНКИ.some((п) => х.has(п.ключ) && п.пасує(g)));
}

const заНазвою = (a, b) => (a.name || "").localeCompare(b.name || "", "uk");
const пусто = (v) => v == null || v === "";

/** Порожні значення завжди в кінці — і при прямому порядку, і при зворотному:
    гра без оцінки не має спливати нагору лише тому, що список перевернули. */
function порівняти(a, b){
  const с = СОРТУВАННЯ.find((x) => x.ключ === ui.sort) || СОРТУВАННЯ[0];
  const x = с.значення(a), y = с.значення(b);
  if(пусто(x) && пусто(y)) return заНазвою(a, b);
  if(пусто(x)) return 1;
  if(пусто(y)) return -1;
  let d = с.текст ? String(x).localeCompare(String(y), "uk") : x - y;
  if(с.спадання) d = -d;
  return (ui.rev ? -d : d) || заНазвою(a, b);
}

/** Чи звужує щось полицю просто зараз: фільтр, пошук або «Приховати».
    Живе тут, поруч із реєстром: додасться фільтр — і це саме його врахує,
    без жодної правки в кнопці «скинути». */
function звужено(){
  return ui.hide.size > 0 || ФІЛЬТРИ.some((ф) => ui[ф.ключ] !== ф.типово);
}

function visible(){
  return shelf()
    .filter((g) => ФІЛЬТРИ.every((ф) => ф.пасує(g, ui[ф.ключ])))
    .sort(порівняти);
}
