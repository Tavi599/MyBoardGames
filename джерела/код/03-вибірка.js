/* ── вибірка й сортування ────────────────────────── */
function effScore(g){
  if(ui.count === "all") return g.score == null ? null : g.score;
  const v = g.byCount ? g.byCount[ui.count] : null;
  return v == null ? null : v;
}
function fitsCount(g, який){
  const с = який == null ? ui.count : який;
  if(с === "all") return true;
  // Поставлена оцінка сильніша за межі: якщо ви так грали — воно грається.
  if(g.byCount && g.byCount[с] != null) return true;
  const {від: mn, до: mx} = склад(g);
  if(mn == null && mx == null) return true;
  if(с === "5+") return mx == null || mx > 5;
  const c = +с;
  return (mn == null || mn <= c) && (mx == null || mx >= c);
}
/* ── що прибрати з полиці зовсім ──────────────────────────────────────
   Це не фільтр, а звуження самої полиці, і різниця тут суттєва: підсумки
   нагорі рахуються по shelf(), тож прибране не потрапляє ні в «ігор на
   полиці», ні в середню оцінку. Саме цього від «приховати» й чекаєш —
   на відміну від фільтра, який лише звужує показане.

   Позначок можна поставити скільки завгодно: доповнення, позбуті коробки
   й те, у що граєш лише онлайн, — це три різні причини не хотіти бачити
   гру в списку, і вони не виключають одна одну. */
const ХОВАНКИ = [
  {ключ: "exp", підпис: "доповнення", пасує: (g) => !!g.expansion},
  {ключ: "позбувся", підпис: "позбуті коробки",
   пасує: (g) => stats(g).indexOf("позбувся") >= 0},
  // «Лише онлайн» — саме лише: коробки, до яких є доступ у мережі й
  // більше ніде. Гру, що стоїть у тебе вдома або в друга, ця позначка
  // не чіпає — те, що в неї можна зіграти ще й онлайн, не робить її
  // менш доступною за столом.
  {ключ: "онлайн", підпис: "лише онлайн",
   пасує: (g) => stats(g).indexOf("онлайн") >= 0
              && stats(g).indexOf("колекція") < 0
              && stats(g).indexOf("чужа") < 0},
  {ключ: "філер", підпис: "маленькі філери",
   пасує: (g) => stats(g).indexOf("філер") >= 0},
];
function shelf(){
  const х = ui.hide;
  if(!х || !х.size) return games;
  return games.filter((g) => !ХОВАНКИ.some((п) => х.has(п.ключ) && п.пасує(g)));
}

const заНазвою = (a, b) => (a.name || "").localeCompare(b.name || "", "uk");
const пусто = (v) => v == null || v === "";

/** Порожні значення завжди в кінці — і при прямому порядку, і при зворотному:
    гра без оцінки не має спливати нагору лише тому, що список перевернули. */
function порівняти(a, b){
  const с = СОРТУВАННЯ.find((x) => x.ключ === ui.sort) || СОРТУВАННЯ[0];
  const x = с.значення(a), y = с.значення(b);
  if(пусто(x) && пусто(y)) return заНазвою(a, b);
  if(пусто(x)) return 1;
  if(пусто(y)) return -1;
  let d = с.текст ? String(x).localeCompare(String(y), "uk") : x - y;
  if(с.спадання) d = -d;
  return (ui.rev ? -d : d) || заНазвою(a, b);
}

/* ── що саме звужує полицю ────────────────────────────────────────────
   Фільтри переїхали за кнопку, і разом з ними зникло з очей те, чому
   коробок раптом дванадцять. Тому звуження описується не одним «так/ні»,
   а переліком: по запису на кожне ввімкнене. З нього живуть і лічильник
   на кнопці, і плашки над списком, і кнопка «скинути все».

   Живе тут, поруч із реєстром: додасться фільтр — і це саме його
   врахує, без жодної правки деінде. */
function звуження(){
  const список = [];
  ФІЛЬТРИ.forEach((ф) => {
    const v = ui[ф.ключ];
    if(v === ф.типово) return;
    // «Місце» їде разом із записом: плашку й лічильник на кнопці заробляє
    // лише те, що сховане в шухляді. Пошук і указник видно й так, і
    // дублювати їх плашкою — це шум там, де має бути відповідь.
    список.push({вид: "фільтр", ключ: ф.ключ, місце: ф.місце,
                 підпис: ф.підпис || "Пошук", значення: підписЗначення(ф, v)});
  });
  ХОВАНКИ.forEach((п) => {
    if(ui.hide.has(п.ключ)) {
      список.push({вид: "хованка", ключ: п.ключ, підпис: "Приховано",
                   значення: п.підпис});
    }
  });
  return список;
}
/** Як назвати вибране значення людською мовою: у стрічки й списку підпис
    лежить у варіантах, у пошуку значення і є підписом. */
function підписЗначення(ф, v){
  if(!ф.варіанти) return String(v);
  const знайдений = ф.варіанти().find((в) => в[0] === v);
  return знайдений ? знайдений[1] : String(v);
}
function звужено(){ return звуження().length > 0; }
/** Знімає одне звуження — те, що назвала плашка. */
function знятиЗвуження(вид, ключ){
  if(вид === "хованка"){ ui.hide.delete(ключ); return; }
  const ф = ФІЛЬТРИ.find((x) => x.ключ === ключ);
  if(ф) ui[ф.ключ] = ф.типово;
}

function visible(){
  return shelf()
    .filter((g) => ФІЛЬТРИ.every((ф) => ф.пасує(g, ui[ф.ключ])))
    .sort(порівняти);
}
