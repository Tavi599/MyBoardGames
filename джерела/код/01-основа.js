/* ── жанри ────────────────────────────────────────────────────────────
   Дві константи, РОДИНИ і ЖАНРИ, вкладає збірка з «джерела/жанри.json» —
   того самого файла, яким звіряється перевірка даних. У самих записах
   лежать слуги BGG («card-game»), а не підписи: підпис можна переписати
   українською заново, і жоден запис від цього не зміниться.

   Родин на весь BGG вісім, тому вони й стали навігацією. Жанрів вісім
   десятків — вони живуть у картці й знаходяться пошуком. */

/** Родина коробки: своя, якщо поставлена, інакше та, що каже BGG.

    Своє поле тут потрібне не про запас. Підрозділ на BGG проставляють
    адміністратори руками, і це не залежить ні від віку гри, ні від
    кількості голосів: «Кіт у коробці» зібрав понад тисячу оцінок і досі
    не має родини, а «Арідник» зі 169 має. Без власного поля такі коробки
    назавжди лишалися б поза жанровою навігацією. */
function familyOf(g){
  return (g.family && g.family.length) ? g.family : (g.bggFamily || []);
}
/** Слуг без підпису показуємо як є: незвичне слово краще за порожнє місце. */
function familyNames(g){ return familyOf(g).map((k) => РОДИНИ[k] || k); }
function genreNames(g){ return (g.bggGenres || []).map((k) => ЖАНРИ[k] || k); }

/* Ключові жанри — те, за чим справді обирають гру на вечір. BGG тримає це
   в двох різних списках: категорія каже, про що гра (фентезі, тварини),
   механіка — як вона грається (кооперативна, драфт, колодобудівна). За
   другим обирають не менше, ніж за першим, тож ключовий жанр збирає
   обидва: гра пасує, якщо має бодай один зі своїх слугів.

   Ніде не зберігаються: виводяться щоразу з bggGenres і bggMech. Тому
   зміна визначення в «жанри.json» діє одразу, без проходу по даних. */
function hasKey(g, к){
  const кат = g.bggGenres || [], мех = g.bggMech || [];
  if(к.склад && !пасуєСклад(g, к.склад)) return false;
  // Жанр лише зі «складом» і без слугів — це умова про саму коробку,
  // і вона вже перевірена вище.
  if(к.склад && !(к.категорії || к.механіки)) return true;
  return (к.категорії || []).some((s) => кат.indexOf(s) >= 0)
      || (к.механіки || []).some((s) => мех.indexOf(s) >= 0);
}
/** Умова «склад» зі словника: {від, до} — межі, у які мусить влізти коробка.
    Так описано «соло»: рівно на одного гравця, «до: 1».

    Механіка BGG для цього не годиться: «solo-solitaire-game» там стоїть у
    всього, у що можна зіграти самому, — на полиці це 28 коробок із 92,
    зокрема ігри на шістьох. Соло-режим і гра-соло — різні речі, тож і
    жанри різні: «соло» рахує склад столу, «соло-режим» — ту механіку. */
function пасуєСклад(g, умова){
  const {від, до} = склад(g);
  if(умова.від != null && (від == null || від < умова.від)) return false;
  if(умова.до != null && (до == null || до > умова.до)) return false;
  return true;
}
/** Ключі жанрів цієї коробки, у порядку словника. */
function keyGenres(g){
  return КЛЮЧОВІ.filter((к) => hasKey(g, к)).map((к) => к.ключ);
}
function keyGenreNames(g){
  return КЛЮЧОВІ.filter((к) => hasKey(g, к)).map((к) => к.підпис);
}

/* ── числа з BGG ──────────────────────────────────────────────────────
   Склад столу, тривалість і «вагу» тягне з BGG етап збору даних; свої
   поля (minP/maxP/minutes/weight) лишаються поверх них. Правило скрізь
   одне: своє число важить більше за чуже. BGG підказує, ти виправляєш. */

/** {від, до} — на скількох гра розрахована. Будь-яка половина може бути null. */
function склад(g){
  return {від: g.minP != null ? g.minP : (g.bggMin != null ? g.bggMin : null),
          до:  g.maxP != null ? g.maxP : (g.bggMax != null ? g.bggMax : null)};
}
/** {від, до} у хвилинах. Свій `minutes` — це одне число, і воно перекриває обидві межі. */
function тривалість(g){
  if(g.minutes != null) return {від: g.minutes, до: g.minutes};
  return {від: g.bggTimeMin != null ? g.bggTimeMin : null,
          до:  g.bggTimeMax != null ? g.bggTimeMax : null};
}
function складність(g){ return g.weight != null ? g.weight : (g.bggWeight != null ? g.bggWeight : null); }

/** Підпис клітинки «5+» знає стелю саме цієї коробки: «до 6», «до 10».
    Понад дюжину підпис не має сенсу: «Картографи» офіційно грають сотнею
    людей, і «до 100» у клітинці на 34 пікселі нічого не пояснює. */
function countLabel(g, c){
  if(c !== "5+") return CLABEL[c];
  const до = склад(g).до;
  return до != null && до > 5 && до <= 12 ? "до " + до : CLABEL["5+"];
}
/** Клітинки складу столу, доречні саме цій коробці. Оцінка, що вже стоїть,
    показується завжди — навіть якщо межі кажуть інакше: те, що людина
    ввела руками, ніколи не зникає через довідник. */
function countsOf(g){
  const {від, до} = склад(g);
  const мін = від == null ? 1 : від;
  const свої = g.byCount || {};
  return COUNTS.filter((c) => {
    if(свої[c] != null) return true;
    if(c === "5+") return до != null && до > 5;
    const n = +c;
    return n >= мін && (до == null || n <= до);
  });
}
/** Тільки ті склади, за які оцінка вже стоїть, — це те, що йде в рядок списку. */
function ratedCounts(g){
  return COUNTS.filter((c) => g.byCount && g.byCount[c] != null);
}
/** [2,3,5,6] → «2–3 · 5–6»: суцільні відрізки склеюються, бо «2, 3, 4, 5»
    читається гірше за «2–5». */
function ranges(набір){
  if(!Array.isArray(набір) || !набір.length) return "";
  const частини = [];
  let a = набір[0], b = набір[0];
  for(let i = 1; i < набір.length; i++){
    if(набір[i] === b + 1){ b = набір[i]; continue; }
    частини.push(a === b ? String(a) : a + "–" + b);
    a = b = набір[i];
  }
  частини.push(a === b ? String(a) : a + "–" + b);
  return частини.join(" · ");
}
/** «2–4 гравці», «від 3», «1 гравець». Порожньо, якщо не знати нічого. */
function playersText(g){
  const {від, до} = склад(g);
  if(від == null && до == null) return "";
  if(від == null) return "до " + до + " " + plural(до, "гравця", "гравців", "гравців");
  if(до == null) return "від " + від;
  if(від === до) return від + " " + plural(від, "гравець", "гравці", "гравців");
  return від + "–" + до + " " + plural(до, "гравець", "гравці", "гравців");
}
/* ── журнал партій ────────────────────────────────────────────────────
   Лічильник `plays` лишається головним числом: «+1 партія» має бути
   одним дотиком і нічого не питати. Журнал `log` — те, що з тих партій
   удалося записати з датою: кожен дотик по «+» кладе туди сьогоднішній
   день, а склад столу й нотатку дописують потім, коли є охота.

   Тому записів у журналі ніколи не більше, ніж партій: партії, зіграні
   до появи журналу, так і лишаються самим числом. Порядок у журналі —
   від давнішої до свіжішої. */
function журнал(g){ return Array.isArray(g.log) ? g.log : []; }
/** Дата останньої записаної партії або null. */
function остання(g){
  const ж = журнал(g);
  return ж.length ? ж[ж.length - 1].on : null;
}
/* «Давно» — це більше за будь-який справжній простій. Сюди потрапляють
   і коробки, які ще не бачили столу, і партії, зіграні до журналу: коли
   дати нема, чесно казати «давно», а не вигадувати число. */
const ДАВНО = 1e6;
/** Скільки днів коробка не була на столі. */
function простій(g, тепер){
  const д = остання(g);
  if(!д) return ДАВНО;
  const мс = (тепер == null ? Date.now() : тепер) - Date.parse(д + "T00:00:00");
  return Math.max(0, Math.floor(мс / 86400000));
}
const МІСЯЦІ = ["січ", "лют", "бер", "квіт", "трав", "черв",
                "лип", "серп", "вер", "жовт", "лист", "груд"];
/** «2026-09-13» → «13 вер». Рік дописуємо лише чужий: свій і так видно. */
function датаКоротко(iso, тепер){
  const ч = String(iso || "").split("-");
  if(ч.length !== 3) return String(iso || "");
  const рік = new Date(тепер == null ? Date.now() : тепер).getFullYear();
  return (+ч[2]) + " " + (МІСЯЦІ[+ч[1] - 1] || ч[1]) +
    (+ч[0] === рік ? "" : " " + ч[0]);
}
/** Сьогодні як «YYYY-MM-DD» за місцевим часом: партію грали ввечері тут,
    а не вранці за Гринвічем. */
function сьогодні(){
  const д = new Date();
  const два = (n) => (n < 10 ? "0" : "") + n;
  return д.getFullYear() + "-" + два(д.getMonth() + 1) + "-" + два(д.getDate());
}
/** Записує партію. День без дати — сьогоднішній; лічильник іде слідом. */
function додатиПартію(g, коли, склад){
  const запис = {on: коли || сьогодні()};
  if(склад) запис.count = склад;
  g.log = журнал(g).concat([запис]).sort((a, b) => (a.on < b.on ? -1 : a.on > b.on ? 1 : 0));
  g.plays = Math.max((+g.plays || 0) + 1, g.log.length);
  return запис;
}
/** Прибирає запис під номером і — разом із партією, яку він рахував.
    Номер, а не дата: за один день партій буває й дві. */
function прибратиПартію(g, і){
  const ж = журнал(g).slice();
  if(!(і >= 0 && і < ж.length)) return false;
  ж.splice(і, 1);
  g.plays = Math.max(ж.length, (+g.plays || 0) - 1);
  if(ж.length) g.log = ж; else delete g.log;
  return true;
}
/** Мінус у лічильнику: спершу з'їдає незаписані партії, і лише коли їх
    не лишилось — найсвіжіший запис журналу. Інакше «−1» стирало б дату,
    якої ти не чіпав. */
function меншеПартій(g){
  const було = +g.plays || 0;
  if(було <= 0) return;
  const ж = журнал(g);
  if(ж.length >= було) прибратиПартію(g, ж.length - 1);
  else g.plays = було - 1;
}

/* ── абетковий указник ────────────────────────────────────────────────
   Дві купки поза українською абеткою: латинка й цифри. Власних кнопок
   вони не варті — «Magic Maze» і «7 чудес. Дуель» на полиці по одній,
   а місце в рядку указника коштує дорого. */
const ЛАТ = "A-Z", ЦИФ = "0-9";
/** Літера, під якою гра стоїть в указнику. Порожньо, якщо назви ще немає:
    щойно додана коробка не мусить створювати кнопку-привида. */
function літера(g){
  const c = String(g.name || "").trim().charAt(0).toUpperCase();
  if(!c) return "";
  if(c >= "0" && c <= "9") return ЦИФ;
  if(c >= "A" && c <= "Z") return ЛАТ;
  return c;
}

/** «45 хв» або «60–90 хв». */
function timeText(g){
  const {від, до} = тривалість(g);
  if(від == null && до == null) return "";
  if(від == null || до == null || від === до) return (від == null ? до : від) + " хв";
  return від + "–" + до + " хв";
}
function plural(n, one, few, many){
  const a = Math.abs(n) % 100, b = a % 10;
  if(a > 10 && a < 20) return many;
  if(b === 1) return one;
  if(b >= 2 && b <= 4) return few;
  return many;
}

